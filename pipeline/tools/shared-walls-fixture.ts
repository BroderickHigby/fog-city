// Writes tests/pipeline/fixtures/shared-walls.json from the cached raw DataSF footprints (W-36):
// in the houses audit's four sample boxes, every pair of footprints whose walls touch in the
// source (closest overlapping walls under TOUCH_M apart), with a point on that wall; and the
// citywide count of cracks (walls TOUCH_M to CRACK_M apart) in the source. The test checks the
// built colliders against it: no touching pair may become a crack, and the city may have no
// more cracks than its source data.
//
//   node pipeline/tools/shared-walls-fixture.ts          (offline: reads pipeline/.cache)

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { toLocal } from "../../src/geo/project.ts";
import { loadWorldConfig } from "../lib/config.ts";
import { centroid, cleanRing, r2, signedArea, type P2 } from "../lib/geom.ts";
import { downloadAll } from "../lib/sources.ts";
import { countCracks, TOUCH_M, wallContacts, type Footprint } from "../lib/wall-contacts.ts";

const ROOT = join(import.meta.dirname, "../..");
/** The houses audit's boxes (qa-world/houses/06-raw-vs-built.ts), local metres [x0, z0, x1, z1]. */
export const BOXES: Record<string, [number, number, number, number]> = {
  "sunset-30th": [-8700, 3800, -8100, 4400],
  "mission-liberty": [-2850, 4000, -2300, 4500],
  marina: [-4300, -1100, -3800, -600],
  "russian-hill": [-2450, -750, -1950, -300],
};

const cfg = loadWorldConfig(ROOT, "sf");
const raw = await downloadAll(cfg, { cacheDir: join(ROOT, "pipeline/.cache"), offline: true });
const rings: Footprint[] = [];
for (const b of raw.buildings) {
  const s = b.shape;
  if (!s) continue;
  // Every part of a multi-part footprint, under the footprint's id (the built world keeps them
  // all, as -1, -2 ... records; parts of one footprint are never a pair).
  const polys = (s.type === "Polygon" ? [s.coordinates] : s.coordinates) as Array<Array<Array<[number, number]>>>;
  for (const p of polys) {
    const ring = cleanRing(p[0]!.map(([lon, lat]) => {
      const q = toLocal(lat, lon);
      return [q.x, q.z] as P2;
    }));
    if (ring.length >= 3 && Math.abs(signedArea(ring)) > 0) rings.push({ id: b.sf16_bldgid, ring });
  }
}
const out: { $comment: string; touching: Record<string, Array<[string, string, P2]>>; rawCracksCitywide: number; footprints: number } = {
  $comment:
    "Generated by pipeline/tools/shared-walls-fixture.ts from the raw DataSF footprints (ynuv-fyni, every part, by footprint id). touching: per sample box, footprint pairs whose closest overlapping walls are under 5 cm apart in the source, with a point on that wall. rawCracksCitywide: pairs whose closest walls are 5 to 60 cm apart in the source (pipeline/lib/wall-contacts.ts).",
  touching: {},
  rawCracksCitywide: 0,
  footprints: rings.length,
};
for (const [name, [x0, z0, x1, z1]] of Object.entries(BOXES)) {
  const sel = rings.filter((f) => {
    const [x, z] = centroid(f.ring);
    return x >= x0 && x <= x1 && z >= z0 && z <= z1;
  });
  const pairs: Array<[string, string, P2]> = [];
  for (const [k, c] of wallContacts(sel)) {
    if (c.gap >= TOUCH_M) continue;
    const [a, b] = k.split("|") as [string, string];
    pairs.push([a, b, [r2(c.at[0]), r2(c.at[1])]]);
  }
  out.touching[name] = pairs.sort((p, q) => (p[0] < q[0] ? -1 : p[0] > q[0] ? 1 : p[1] < q[1] ? -1 : 1));
  console.log(`${name}: ${sel.length} footprints, ${pairs.length} touching pairs`);
}
out.rawCracksCitywide = countCracks(wallContacts(rings));
console.log(`citywide: ${rings.length} footprints, ${out.rawCracksCitywide} cracks in the source`);
writeFileSync(join(ROOT, "tests/pipeline/fixtures/shared-walls.json"), `${JSON.stringify(out)}\n`);
